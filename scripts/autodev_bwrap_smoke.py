#!/usr/bin/env python3
"""Live bubblewrap smoke on disposable CI; no accounts or project secrets."""
import hashlib
import importlib.util
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("autodev_supervisor", HERE / "autodev_supervisor.py")
autodev = importlib.util.module_from_spec(spec)
spec.loader.exec_module(autodev)


def main():
    bwrap = shutil.which("bwrap")
    if not bwrap or Path(bwrap).resolve() != Path("/usr/bin/bwrap"):
        raise RuntimeError("Expected distro-packaged /usr/bin/bwrap")
    pinned = Path(bwrap)
    digest = hashlib.sha256(pinned.read_bytes()).hexdigest()
    with tempfile.TemporaryDirectory(prefix="autodev-live-bwrap-") as d:
        scratch = Path(d)
        (scratch / "scripts").mkdir()
        (scratch / "scripts" / "test_isolation.py").write_text(
            "import unittest\n"
            "from pathlib import Path\n"
            "class IsolationTests(unittest.TestCase):\n"
            "    def test_source_readonly(self):\n"
            "        self.assertTrue(Path('/workspace/scripts/test_isolation.py').is_file())\n"
            "        with self.assertRaises(OSError):\n"
            "            Path('/workspace/scripts/forbidden').write_text('mutation')\n"
            "    def test_host_home_and_ssh_unavailable(self):\n"
            "        self.assertFalse(Path('/home/runner').exists())\n"
            "        self.assertFalse(Path('/root/.ssh').exists())\n"
            "    def test_own_temp_is_writable(self):\n"
            "        p = Path('/tmp/allowed')\n"
            "        p.write_text('ok')\n"
            "        self.assertEqual(p.read_text(), 'ok')\n",
            encoding="utf-8",
        )
        try:
            autodev.project_test_gate(
                scratch, pinned, digest, timeout=60, recipe="python-unittest",
            )
        except autodev.Refused:
            # A fixed, credential-free probe distinguishes Ubuntu/AppArmor
            # namespace denial from the supervisor's own mount recipe.
            probe = subprocess.run(
                [str(pinned), "--unshare-all", "--ro-bind", "/usr", "/usr",
                 "--", "/usr/bin/true"],
                stdout=subprocess.DEVNULL, stderr=subprocess.PIPE,
                timeout=8, check=False,
                env={"PATH": "/usr/bin:/bin", "HOME": "/tmp"},
            )
            diagnostic = probe.stderr.decode("utf-8", "replace")[:220]
            diagnostic = diagnostic.replace("\n", " ").replace("\r", " ")
            print("BWRAP_PROBE_EXIT", probe.returncode, diagnostic,
                  file=sys.stderr)
            raise
        if (scratch / "scripts" / "forbidden").exists():
            raise RuntimeError("wrote through a supposedly read-only mount")
    if not Path("/usr/bin/cargo").is_file() or not Path("/usr/bin/rustc").is_file():
        raise RuntimeError("System Rust toolchain not installed")
    with tempfile.TemporaryDirectory(prefix="autodev-live-cargo-") as d:
        scratch = Path(d)
        (scratch / "src").mkdir()
        (scratch / "Cargo.toml").write_text(
            '[package]\nname = "isolated-smoke"\nversion = "0.1.0"\nedition = "2021"\n',
            encoding="utf-8",
        )
        (scratch / "Cargo.lock").write_text(
            '# This file is automatically @generated by Cargo.\nversion = 3\n\n'
            '[[package]]\nname = "isolated-smoke"\nversion = "0.1.0"\n',
            encoding="utf-8",
        )
        (scratch / "src" / "lib.rs").write_text(
            '#[cfg(test)] mod tests { #[test] fn fixed() { assert_eq!(2 + 2, 4); } }\n',
            encoding="utf-8",
        )
        autodev.project_test_gate(
            scratch, pinned, digest, timeout=100, recipe="rust-cargo-test",
        )
        if (scratch / "target").exists():
            raise RuntimeError("Cargo target escaped isolated /tmp")
    print("LIVE_CARGO_OFFLINE_SANDBOX_PASS")
    print("LIVE_BWRAP_SANDBOX_PASS")


if __name__ == "__main__":
    try:
        main()
    except (autodev.Refused, RuntimeError, OSError) as error:
        print("LIVE_BWRAP_SANDBOX_FAIL:", type(error).__name__, file=sys.stderr)
        sys.exit(2)
